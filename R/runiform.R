#' Generate uniform pseudorandom numbers using the Lewis generator
#'
#' @description
#' Generates a sequence of pseudorandom numbers from a continuous uniform
#' distribution on the interval \eqn{[0,1)}. The function uses the
#' Lewis--Goodman--Miller multiplicative congruential generator, with
#' multiplier \eqn{a = 7^5 = 16807} and modulus
#' \eqn{m = 2^{31} - 1}.
#'
#' @param n A positive integer giving the number of pseudorandom values to
#'   generate.
#'
#' @return A numeric vector of length \code{n} containing pseudorandom values
#'   in the interval \eqn{[0,1)}.
#'
#' @details
#' An initial seed is selected from the current time and reduced modulo 10000.
#' Starting from this seed, the internal integer sequence is generated by
#' \deqn{X_i = 16807 X_{i-1} \bmod (2^{31} - 1),}
#' and each returned value is obtained as
#' \deqn{U_i = X_i / (2^{31} - 1).}
#'
#' The function is a convenient wrapper around \code{\link{gcong}} with an
#' additive constant equal to zero.
#'
#' @examples
#' x <- runiform(10)
#' x
#'
#' @seealso \code{\link{gcong}}, \code{\link{uniftest}},
#'   \code{\link{independence}}
#'
#' @export
runiform <- function(n){
  seed <- sample(as.numeric(Sys.time()), 1) %% 10000
  gcong(n = n, seed = seed, a = 7^5, m = 2^31 - 1)
}
